import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { MongoClient } from 'mongodb';
import { MongoMemoryReplSet } from 'mongodb-memory-server';
import { createApp, initialize, seedSynthetic } from '../src/app.mjs';

const binary = process.env.MONGOMS_SYSTEM_BINARY;
test('password cookie lifecycle uses real scoped Mongo identity', async t => {
  const repl = await MongoMemoryReplSet.create({ binary: { systemBinary: binary, version: '7.0.14' }, replSet: { count: 1, storageEngine: 'wiredTiger' }, instanceOpts: [{ args: ['--wiredTigerCacheSizeGB', '0.25', '--oplogSize', '128'] }] });
  const client = await new MongoClient(repl.getUri()).connect();
  const db = client.db(`portfolio_test_${randomUUID().replaceAll('-', '')}`);
  const marker = randomUUID();
  await db.collection('ownedRun').insertOne({ _id: marker });
  let server;
  t.after(async () => { if (server) await new Promise(r => server.close(r)); assert.ok(await db.collection('ownedRun').findOne({ _id: marker })); await db.dropDatabase(); await client.close(); await repl.stop(); });
  const runtime = await initialize({ client, db });
  const password = randomUUID();
  const seeded = await seedSynthetic(runtime, { password });
  const app = createApp(runtime, { origins: ['http://localhost:4173'] });
  server = app.listen(0, '127.0.0.1');
  await new Promise(r => server.once('listening', r));
  const base = `http://127.0.0.1:${server.address().port}`;
  async function req(path, { method = 'GET', body, cookie, headers = {} } = {}) {
    const response = await fetch(base + path, { method, headers: { ...(body ? { 'content-type': 'application/json' } : {}), ...(method !== 'GET' ? { origin: 'http://localhost:4173' } : {}), ...(cookie ? { cookie } : {}), ...headers }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, body: await response.json(), cookie: response.headers.get('set-cookie') };
  }
  await t.test('rejects wrong passwords and identity headers', async () => {
    assert.equal((await req('/api/session/login', { method: 'POST', body: { username: 'alpha.owner', password: 'wrong' } })).status, 401);
    assert.equal((await req('/api/session/me', { headers: { 'x-user-id': seeded[0].userId } })).status, 401);
  });
  const login = await req('/api/session/login', { method: 'POST', body: { username: 'alpha.owner', password } });
  assert.equal(login.status, 200); assert.match(login.cookie, /HttpOnly/); assert.match(login.cookie, /SameSite=Lax/);
  const cookie = login.cookie.split(';')[0];
  assert.equal((await req('/api/session/me', { cookie })).body.data.scope.tenantId, seeded[0].tenantId);
  await t.test('CRM accounts persist and isolate two tenants with transactional stages', async () => {
    const other = await req('/api/session/login', { method: 'POST', body: { username: 'beta.owner', password } });
    const beta = other.cookie.split(';')[0];
    const created = await req('/api/crm/accounts', { method: 'POST', cookie, body: { name: 'Synthetic customer' } });
    assert.equal(created.status, 201);
    const id = created.body.data._id;
    assert.equal((await req(`/api/crm/accounts/${id}`, { cookie: beta })).status, 404);
    assert.equal((await req('/api/crm/accounts', { cookie: beta })).body.data.length, 0);
    assert.equal((await req('/api/crm/accounts', { cookie, headers: { 'x-tenant-id': seeded[1].tenantId } })).status, 403);
    assert.equal((await req('/api/crm/accounts', { method: 'POST', cookie, body: { name: 'forged', plant_id: seeded[1].plantId } })).status, 403);
    assert.equal((await req('/api/crm/accounts', { method: 'POST', cookie, body: { name: 'blocked' }, headers: { origin: 'https://evil.example' } })).status, 403);
    const contact = await req(`/api/crm/accounts/${id}/contacts`, { method: 'POST', cookie, body: { name: 'Synthetic contact', email: 'demo@example.invalid' } });
    assert.equal(contact.status, 201);
    assert.equal((await req(`/api/crm/accounts/${id}/contacts`, { cookie })).body.data.length, 1);
    assert.equal((await req(`/api/crm/accounts/${id}/contacts`, { method: 'POST', cookie, body: { name: 'Conflict', accountId: randomUUID() } })).status, 400);
    const post = body => req('/api/crm/opportunities', { method: 'POST', cookie, body });
    assert.equal((await post({ accountId: randomUUID(), amount: '1.00', currency: 'USD' })).status, 404);
    assert.equal((await post({ accountId: id, amount: 0.1, currency: 'USD' })).status, 400);
    assert.equal((await post({ accountId: id, amount: '1.001', currency: 'USD' })).status, 400);
    assert.equal((await post({ accountId: id, amount: '1.00', currency: 'XXX' })).status, 400);
    assert.equal((await post({ accountId: id, ownerId: seeded[1].userId, amount: '1.00', currency: 'USD' })).status, 403);
    assert.equal((await post({ accountId: id, amount: '1x00', currency: 'USD' })).status, 400);
    assert.equal((await post({ accountId: id, amount: '1', currency: 'JPY' })).status, 201);
    assert.equal((await post({ accountId: id, amount: '1.001', currency: 'KWD' })).status, 201);
    const opp = await post({ accountId: id, amount: '90071992547409931234.10', currency: 'USD' });
    assert.equal(opp.status, 201); assert.equal(opp.body.data.amount, '90071992547409931234.10');
    const oid = opp.body.data._id;
    assert.equal((await req(`/api/crm/opportunities/${oid}`, { cookie: beta })).status, 404);
    const stage = body => req(`/api/crm/opportunities/${oid}/stage`, { method: 'POST', cookie, body });
    const auditBefore = await db.collection('crmAudit').countDocuments();
    const changed = await stage({ expectedVersion: 1, stage: 'QUALIFIED', reason: 'Synthetic qualification' });
    assert.equal(changed.status, 200); assert.equal(changed.body.data.version, 2);
    assert.equal((await stage({ expectedVersion: 1, stage: 'WON', reason: 'stale retry' })).status, 409);
    assert.equal(await db.collection('crmAudit').countDocuments(), auditBefore + 1);
    assert.equal((await req(`/api/crm/opportunities/${oid}`, { cookie })).body.data.history.length, 2);
    assert.equal((await stage({ expectedVersion: 2, stage: 'QUOTING', reason: 'retry current' })).status, 200);
    const concurrent = await Promise.all([stage({ expectedVersion: 3, stage: 'WON', reason: 'Concurrent winner' }), stage({ expectedVersion: 3, stage: 'LOST', reason: 'Concurrent loser' })]);
    assert.deepEqual(concurrent.map(r => r.status).sort(), [200, 409]);
    assert.equal((await req(`/api/crm/opportunities/${oid}`, { cookie })).body.data.history.length, 4);
    const beforeRollback = await db.collection('accounts').countDocuments();
    await db.command({ collMod: 'crmAudit', validator: { forbidden: { $exists: true } }, validationLevel: 'strict' });
    assert.equal((await req('/api/crm/accounts', { method: 'POST', cookie, body: { name: 'Must roll back' } })).status, 500);
    assert.equal(await db.collection('accounts').countDocuments(), beforeRollback);
    await db.command({ collMod: 'crmAudit', validator: {} });
    assert.equal((await req('/api/crm/accounts', { cookie, headers: { 'x-plant-id': randomUUID() } })).status, 403);
    assert.equal((await req('/api/crm/accounts?tenant_id=' + seeded[1].tenantId, { cookie })).status, 403);
    assert.equal((await req('/api/crm/accounts?cursor=broken', { cookie })).status, 400);
    assert.equal((await req('/api/crm/accounts', { method: 'POST', cookie, body: { name: 'Second' } })).status, 201);
    const page = await req('/api/crm/accounts?limit=1', { cookie });
    assert.equal(page.body.data.length, 1); assert.ok(page.body.page.nextCursor);
    const page2 = await req(`/api/crm/accounts?limit=1&cursor=${page.body.page.nextCursor}`, { cookie });
    assert.equal(page2.body.data.length, 1); assert.notEqual(page2.body.data[0]._id, page.body.data[0]._id);
    assert.equal((await req('/api/crm/accounts?limit=0', { cookie })).status, 400);
    const plant = randomUUID();
    await runtime.foundation.provisionPlant({ id: plant, tenantId: seeded[0].tenantId, legalEntityId: (await db.collection('plants').findOne({ _id: seeded[0].plantId })).legalEntityId });
    await db.collection('accounts').insertOne({ _id: randomUUID(), tenantId: seeded[0].tenantId, plantId: plant, name: 'Other plant' });
    assert.equal((await req('/api/crm/accounts', { cookie })).body.data.length, 2);
    const publicFoundation = runtime.foundation;
    runtime.foundation = { ...publicFoundation, authorize: async (...args) => {
      const grant = await publicFoundation.authorize(...args);
      await publicFoundation.invalidateMembership({ tenantId: seeded[1].tenantId, membershipId: seeded[1].membershipId, expectedVersion: 1, active: false });
      return grant;
    } };
    const beforeRevokedWrite = await db.collection('accounts').countDocuments();
    assert.equal((await req('/api/crm/accounts', { method: 'POST', cookie: beta, body: { name: 'Revoked during authorization' } })).status, 403);
    assert.equal(await db.collection('accounts').countDocuments(), beforeRevokedWrite);
    runtime.foundation = publicFoundation;
    assert.equal((await req('/api/crm/accounts', { cookie: beta })).status, 401);
  });
  await t.test('logout revokes captured cookie', async () => {
    assert.equal((await req('/api/session/logout', { method: 'POST', cookie, body: {} })).status, 200);
    assert.equal((await req('/api/session/me', { cookie })).status, 401);
  });
});
