import { spawn, execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, openSync, closeSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const root = process.env.QA_RUNTIME_ROOT;
const sourceFiles = execFileSync('git',['ls-files','apps/portfolio-api/src','packages','apps/portfolio-api/test/support/owned-mongo.mjs'],{encoding:'utf8'}).trim().split('\n');
const hashSources = () => Object.fromEntries(sourceFiles.map(p=>[p,createHash('sha256').update(readFileSync(p)).digest('hex')]));
const before = hashSources(), head = execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
const original = execFileSync('git',['show','9269ae5:packages/tenant-lifecycle/automation-recovery-v15.test.mjs'],{encoding:'utf8'});
const current = readFileSync('packages/tenant-lifecycle/automation-recovery-v15.test.mjs','utf8');
assert.equal(current,original);
assert.equal(readFileSync('apps/portfolio-api/test/support/owned-mongo.mjs','utf8'),execFileSync('git',['show','9269ae5:apps/portfolio-api/test/support/owned-mongo.mjs'],{encoding:'utf8'}));
const allowed = ['packages/tenant-lifecycle/automation-recovery-v15.test.mjs','checkpoints/acceptance-fixes/platform/fixture-guards.test.mjs'];
const selected = process.argv.slice(2);
assert.ok(selected.every(p=>allowed.includes(p)));
const args = ['--import','./checkpoints/acceptance-fixes/platform/cold-20261101/register-profile.mjs','--test','--test-concurrency=1','--test-reporter=tap',...(selected.length?selected:allowed)];
const instrumentation = ['runtime.cjs','register-profile.mjs','run-exclusive.mjs'].map(p=>'checkpoints/acceptance-fixes/platform/cold-20261101/'+p);
const command = {startedUtc:new Date().toISOString(),head,cwd:process.cwd(),command:process.execPath,args,outerTimeoutMs:420000,sourceManifest:before,instrumentationManifest:Object.fromEntries(instrumentation.map(p=>[p,createHash('sha256').update(readFileSync(p)).digest('hex')])),noConcurrentProbes:'No source reads/generation/capability probes by owning agent during native fixture. OS identity and passive command/resource telemetry only.'};
writeFileSync(join(root,'command.json'),JSON.stringify(command,null,2));
const output = openSync(join(root,'suite.tap'),'w'), started = Date.now();
const child = spawn(process.execPath,args,{stdio:['ignore',output,output],windowsHide:true});
const deadline = setTimeout(()=>child.kill('SIGTERM'),command.outerTimeoutMs);
let error;
child.once('error',e=>error=e.message);
