const capacityFloorRespected=!events.some(e=>e.belowRamFloor);
const result={finishedUtc:new Date().toISOString(),durationMs:Date.now()-started,pid:child.pid,code,signal,error,sourceUnchanged:JSON.stringify(before)===JSON.stringify(after),capacityFloorRespected};
writeFileSync(join(root,'result.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
process.exitCode=code===0&&result.sourceUnchanged&&capacityFloorRespected?0:1;
